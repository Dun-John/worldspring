//! Temples' footprints, built of pieces (`Building::parts`) on the largest rectangle their lot holds
//! (square to the lot, whole squares each way): a big temple (`BIG` or more) a cross, its nave and
//! choir along the rectangle (`PartKind::Body`), its transept across it (`PartKind::Wing`), a round
//! apse at the end away from its door (`PartKind::Apse`); a small one (`SMALL` or more) a single hall
//! with the apse, as a shrine in a town or a city is (smaller: `shrine_plan`); smaller ones keep their
//! lot. The door's end is the one nearer a street (else the
//! apse toward the east). The lot's ground the temple leaves is open ground round it. A town laid
//! out anew by hand shapes each temple again from its lot (`wards::inherit` knows a temple as
//! generated by the footprint its lot gives: `shape`).

use super::geom::{P, add, area, dist, dot, mul, obb, sub, union_outline};
use super::palace::{Sides, largest_rect};
use super::{Building, Layout, Part, PartKind, Structure, Ward, catalog};
use crate::t0::settle::Tier;

/// The least rectangle (squares: long, short) a big temple stands on: a nave 5 squares wide (an aisle
/// each side of its arcades) with its transept two squares out each way, 5 rows long before the
/// crossing (4 rows), its sanctuary (4).
pub const BIG: (usize, usize) = (13, 9);
/// The least a small temple stands on: a hall 5 squares wide with its apse (a pew each side of the aisle
/// up its middle, the stairs down a square in from its walls beside them).
pub const SMALL: (usize, usize) = (8, 5);

/// A cross plan's dimensions along its axis (squares, from its door): the nave's rows, the
/// transept's (and how far it reaches out past the body each side), the choir's, the sanctuary's
/// (its apse rounding the last `width / 2`); the body's width.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Cross {
    pub nave: usize,
    pub transept: usize,
    pub arm: usize,
    pub choir: usize,
    pub sanctuary: usize,
    pub width: usize,
}

impl Cross {
    pub fn len(&self) -> usize {
        self.nave + self.transept + self.choir + self.sanctuary
    }
}

/// Whether a building is a temple.
pub fn is_temple(b: &Building) -> bool {
    b.func.is_some_and(|f| catalog::CATALOG[f as usize].key == "temple")
}

/// Whether a building is a shrine.
pub fn is_shrine(b: &Building) -> bool {
    b.func.is_some_and(|f| catalog::CATALOG[f as usize].key == "shrine")
}

/// A temple (or a town's shrine: `shrine_plan`) shaped here: its pieces end in an apse.
pub fn shaped(b: &Building) -> bool {
    (is_temple(b) || is_shrine(b)) && b.parts.iter().any(|p| p.kind == PartKind::Apse)
}

/// A big temple's cross as it was shaped (`shape`), measured from its pieces (moved or turned with
/// them by hand too); None for any other building.
pub fn cross_of(b: &Building) -> Option<Cross> {
    if !shaped(b) {
        return None;
    }
    let body = &b.parts.first().filter(|p| p.kind == PartKind::Body && p.poly.len() == 4)?.poly;
    let wing = &b.parts.iter().find(|p| p.kind == PartKind::Wing && p.poly.len() == 4)?.poly;
    let (es, et) = (unit(sub(body[1], body[0])), unit(sub(body[3], body[0])));
    let sq = |x: f64| crate::core::round(x / 5.0).max(0.0) as usize;
    let width = sq(dist(body[0], body[3]));
    let len = crate::core::round(dist(body[0], body[1]) / 5.0 + 0.5 * width as f64) as usize;
    let (nave, transept, arm) = (sq(dot(sub(wing[0], body[0]), es)), sq(dist(wing[0], wing[1])), sq(-dot(sub(wing[0], body[0]), et)));
    let sanctuary = width.div_ceil(2) + 1;
    let choir = len.checked_sub(nave + transept + sanctuary)?;
    Some(Cross { nave, transept, arm, choir, sanctuary, width })
}

/// The look of a temple's pieces (the god's statue, its candle stands, its screen and side altars:
/// `interior::GOD_LOOKS`) for the god in its name ("Temple of the Sun"; a shrine's or a monastery's
/// too), by the god's kind: the Sun and the Morning Lord, the Dawn, the Moon and the Veiled Lady,
/// the Deep Sea, the Storm, the Forge, the Harvest and the Hearth, the Seven and the Watcher. A name
/// with no god (renamed, or none): by its id.
pub fn god_look(b: &Building) -> u8 {
    const LOOK: [u8; 12] = [1, 0, 6, 3, 5, 2, 7, 7, 6, 4, 2, 0];
    let god = b.name.as_deref().and_then(|n| catalog::DEITY.iter().position(|d| n.ends_with(&format!(" of {d}"))));
    god.map_or((b.id % 8) as u8, |g| LOOK[g])
}

/// The god's kinds a temple's pieces are drawn for (`god_look`), by look.
pub const GOD_KINDS: [&str; 8] = ["the Sun and the Morning Lord", "the Dawn", "the Moon and the Veiled Lady", "the Deep Sea", "the Storm", "the Forge", "the Harvest and the Hearth", "the Seven and the Watcher"];

/// A big temple's plan on a rectangle `l` squares long and `s` across (`BIG` or more), if one fits:
/// its transept as wide as the rectangle (15 squares at most, three quarters of its length), its arms
/// 2 squares (3 from 13 across), the body between them; the sanctuary as deep as half the body's
/// width and a square more, the transept 4 rows (5 for a body over 7 wide), a nave of 5 rows or more,
/// a choir between the crossing and the sanctuary from a third of what is left over (3 rows at most).
/// The plan's length is the rectangle's, to twice its width and 6 more.
pub fn cross_plan(l: usize, s: usize) -> Option<Cross> {
    if l < BIG.0 || s < BIG.1 {
        return None;
    }
    let most = s.min(15).min(3 * l / 4);
    (BIG.1..=most).rev().find_map(|t| {
        let arm = if t >= 13 { 3 } else { 2 };
        let width = t - 2 * arm;
        let len = l.min(2 * t + 6);
        let sanctuary = width.div_ceil(2) + 1;
        let transept = if width <= 7 { 4 } else { 5 };
        if len < transept + sanctuary + 5 {
            return None;
        }
        let choir = ((len - transept - sanctuary - 5) / 3).min(3);
        Some(Cross { nave: len - transept - choir - sanctuary, transept, arm, choir, sanctuary, width })
    })
}

/// A small temple's hall on a rectangle `l` by `s` squares (`SMALL` or more): as wide as it (9 at most,
/// 0.6 of its length), as long (to three times its width and 2 more): its width and length.
pub fn hall_plan(l: usize, s: usize) -> Option<(usize, usize)> {
    if l < SMALL.0 || s < SMALL.1 {
        return None;
    }
    let w = s.min(9).min(crate::core::round(0.6 * l as f64) as usize).max(SMALL.1);
    let len = l.min(3 * w + 2);
    (2 * len >= w + 6).then_some((w, len))
}

/// A shrine's hall in a town or a city on a rectangle `l` by `s` squares (`SMALL` or more): a small
/// temple's scaled down, 5 squares wide and 10 long at most: its width and length.
pub fn shrine_plan(l: usize, s: usize) -> Option<(usize, usize)> {
    (l >= SMALL.0 && s >= SMALL.1).then_some((SMALL.1, l.min(10)))
}

/// A temple's footprint on its lot `poly` (world ft, convex): its outline and its pieces (the body
/// first, then the transept, then the apse), its door at the rectangle's end along its first long
/// side's way from its first corner, or the other end with `back`; a shrine's (`shrine`) a hall
/// (`shrine_plan`). None for a lot too small for a small temple, or not convex.
pub fn shape(poly: &[P], back: bool, shrine: bool) -> Option<(Vec<P>, Vec<Part>)> {
    if poly.len() < 3 || !convex(poly) {
        return None;
    }
    let ccw = area(poly) > 0.0;
    let u = obb(poly).axis;
    let sides = Sides { least: 20.0, long: 35.0, most_short: 300.0, most_long: 300.0, most_area: f64::MAX };
    let (r, _) = largest_rect(poly, u, false, sides, ccw)?;
    let (a, b) = (dist(r[0], r[1]), dist(r[1], r[2]));
    let (along, lr, sr) = if a >= b { (unit(sub(r[1], r[0])), a, b) } else { (unit(sub(r[2], r[1])), b, a) };
    let (lsq, ssq) = (crate::core::round(lr / 5.0) as usize, crate::core::round(sr / 5.0) as usize);
    let c = mul(add(add(r[0], r[1]), add(r[2], r[3])), 0.25);
    let es = if back { mul(along, -1.0) } else { along };
    let et = [-es[1], es[0]];
    // (Frame squares (s from the door, t across from the axis) to world ft, about the rectangle's
    // middle.)
    let (len, width, cross) = match cross_plan(lsq, ssq).filter(|_| !shrine) {
        Some(x) => (x.len(), x.width, Some(x)),
        None => {
            let (w, l) = if shrine { shrine_plan(lsq, ssq)? } else { hall_plan(lsq, ssq)? };
            (l, w, None)
        }
    };
    let o = sub(c, mul(es, 2.5 * len as f64));
    let at = |s: f64, t: f64| add(o, add(mul(es, 5.0 * s), mul(et, 5.0 * t)));
    let (l, h) = (len as f64, 0.5 * width as f64);
    // The apse rounds the last half width: the body up to it, the apse from a square before it
    // (so no square's middle lies on the line between them).
    let a0 = l - h;
    let rect = |s0: f64, s1: f64, t0: f64, t1: f64| vec![at(s0, t0), at(s1, t0), at(s1, t1), at(s0, t1)];
    let mut parts = vec![Part { poly: rect(0.0, a0, -h, h), kind: PartKind::Body }];
    if let Some(x) = cross {
        let (s0, half) = (x.nave as f64, 0.5 * (x.width + 2 * x.arm) as f64);
        parts.push(Part { poly: rect(s0, s0 + x.transept as f64, -half, half), kind: PartKind::Wing });
    }
    let mut apse = vec![at(a0 - 1.0, -h)];
    for k in 0..=APSE_SIDES {
        let th = std::f64::consts::PI * (k as f64 / APSE_SIDES as f64 - 0.5);
        apse.push(at(a0 + h * libm::cos(th), h * libm::sin(th)));
    }
    apse.push(at(a0 - 1.0, h));
    parts.push(Part { poly: apse, kind: PartKind::Apse });
    let outline = union_outline(&parts.iter().map(|p| p.poly.clone()).collect::<Vec<_>>())?;
    Some((outline, parts))
}

/// The apse's half circle in this many straight pieces (inside the circle; no square's middle lies
/// between it and them for a body up to 9 squares wide).
const APSE_SIDES: usize = 16;

fn unit(d: P) -> P {
    mul(d, 1.0 / super::geom::len(d).max(1e-9))
}

/// Whether a polygon turns one way only.
fn convex(poly: &[P]) -> bool {
    let n = poly.len();
    let turns: Vec<f64> = (0..n).map(|k| super::geom::cross(sub(poly[(k + 1) % n], poly[k]), sub(poly[(k + 2) % n], poly[(k + 1) % n]))).collect();
    turns.iter().all(|&t| t >= -1e-6) || turns.iter().all(|&t| t <= 1e-6)
}

/// Each temple of layout `l` (world ft) on its lot shaped (`shape`): its door at the end whose way
/// out (on its axis, else a porch in a long wall by it) reaches a street (`street_reach`), the end
/// nearer a street (within 80 ft) first, else its apse toward the east; in a town laid out anew, a
/// temple whose lot gives it as `generated` has it (either end) as it was. Not a castle's, nor one
/// already in pieces. Its lot its ground (`Layout::grounds`).
pub(super) fn shape_all(l: &mut Layout, generated: Option<&Layout>) {
    let street_d = |p: P| l.roads.iter().flat_map(|(pts, _, w)| pts.windows(2).map(move |s| super::geom::seg_dist(p, s[0], s[1]) - 0.5 * w)).fold(f64::MAX, f64::min);
    let mut done: Vec<(usize, Vec<P>, Vec<Part>)> = Vec::new();
    for (k, b) in l.buildings.iter().enumerate() {
        let shrine = is_shrine(b) && l.tier >= Tier::Town;
        if !(is_temple(b) || shrine) || b.structure != Structure::Roofed || b.ward == Ward::Castle || !b.parts.is_empty() {
            continue;
        }
        let Some((p0, q0)) = shape(&b.poly, false, shrine) else { continue };
        let Some((p1, q1)) = shape(&b.poly, true, shrine) else { continue };
        // (Each way's door end: the body's first edge's middle.)
        let door = |q: &[Part]| mul(add(q[0].poly[0], q[0].poly[3]), 0.5);
        let apse_east = |q: &[Part]| dot(sub(q[q.len() - 1].poly[1 + APSE_SIDES / 2], door(q)), [1.0, 0.0]);
        let same = |p: &[P], g: &Building| p.len() == g.poly.len() && p.iter().zip(&g.poly).all(|(a, c)| dist(*a, *c) < 0.01);
        let was = generated.and_then(|g| g.building(b.id as usize)).filter(|g| shaped(g) && g.func == b.func);
        let (d0, d1) = (street_d(door(&q0)), street_d(door(&q1)));
        let (w0, w1) = if was.is_some() { ((false, false), (false, false)) } else { (ways_out(l, b.id, &p0, &q0), ways_out(l, b.id, &p1, &q1)) };
        let first = match (d0 < 80.0, d1 < 80.0) {
            _ if was.is_some_and(|g| same(&p0, g)) => true,
            _ if was.is_some_and(|g| same(&p1, g)) => false,
            _ if w0 != w1 => w0 > w1,
            (true, false) => true,
            (false, true) => false,
            (true, true) if (d0 - d1).abs() > 2.0 => d0 < d1,
            _ => apse_east(&q0) >= apse_east(&q1),
        };
        let (p, q) = if first { (p0, q0) } else { (p1, q1) };
        done.push((k, p, q));
    }
    for (k, p, q) in done {
        let b = &mut l.buildings[k];
        let lot = std::mem::replace(&mut b.poly, p);
        b.parts = q;
        let id = b.id;
        l.grounds.push((id, lot));
    }
}

/// A temple's ways out at its door's end (footprint `outline`, pieces `parts` as `shape` gives them)
/// onto ground that reaches a street (`street_reach`): on its axis, through a porch in a long wall by
/// it.
fn ways_out(l: &Layout, id: u32, outline: &[P], parts: &[Part]) -> (bool, bool) {
    let body = &parts[0].poly;
    let (es, et) = (unit(sub(body[1], body[0])), unit(sub(body[3], body[0])));
    let w = crate::core::round(dist(body[0], body[3]) / 5.0) as isize;
    let r = street_reach(l, id, outline, outline, REACH_PAD);
    // (Frame square (s, t) from the door's end's first corner: its middle.)
    let ok = |s: isize, t: isize| r.at(add(body[0], add(mul(es, 5.0 * (s as f64 + 0.5)), mul(et, 5.0 * (t as f64 + 0.5)))));
    let ax = (w - 1) / 2;
    let axis = ok(-1, ax) || ok(-1, w - 1 - ax);
    let porch = (1..3).any(|s| ok(s, -1) || ok(s, w));
    (axis, porch)
}

/// A shrine (or a temple) of layout `l` (world ft, on its lot: before `shape_all`) with no open ground
/// beside it that reaches a street (`street_reach`: shut in a block's middle) changes places with the
/// nearest home (within 150 ft, as big as three quarters of it or more) that has: its function, name,
/// storeys and home's kind. In a town laid out anew, not one that stands as `generated` (its id and
/// function the same: moved there already, or kept there).
pub(super) fn reach_streets(l: &mut Layout, generated: Option<&Layout>) {
    // (Open ground beside outline `poly` that reaches a street: a point 2.5 ft out from every 2.5 ft
    // of each side.)
    let beside = |l: &Layout, b: &Building| {
        let r = street_reach(l, b.id, &b.poly, &b.poly, REACH_PAD);
        let n = b.poly.len();
        let ccw = area(&b.poly) > 0.0;
        (0..n).any(|k| {
            let (a, c) = (b.poly[k], b.poly[(k + 1) % n]);
            let e = sub(c, a);
            let out = mul(unit([e[1], -e[0]]), if ccw { 2.5 } else { -2.5 });
            let m = crate::core::ceil(super::geom::len(e) / 2.5).max(1.0) as usize;
            (0..m).any(|q| r.at(add(add(a, mul(e, (q as f64 + 0.5) / m as f64)), out)))
        })
    };
    let mut moved: Vec<usize> = Vec::new();
    for k in 0..l.buildings.len() {
        let b = &l.buildings[k];
        let kept = generated.is_some_and(|g| g.building(b.id as usize).is_some_and(|o| o.func == b.func));
        if !(is_shrine(b) || is_temple(b)) || b.structure != Structure::Roofed || !b.parts.is_empty() || b.ward == Ward::Castle || kept || moved.contains(&k) || beside(l, b) {
            continue;
        }
        let (c, a) = (super::geom::centroid(&b.poly), area(&b.poly).abs());
        let mut homes: Vec<(f64, usize)> = (0..l.buildings.len())
            .filter(|&j| {
                let o = &l.buildings[j];
                o.func.is_none() && o.keep.is_none() && o.parts.is_empty() && o.structure == Structure::Roofed && !moved.contains(&j) && area(&o.poly).abs() >= 0.75 * a
            })
            .map(|j| (dist(super::geom::centroid(&l.buildings[j].poly), c), j))
            .filter(|&(d, _)| d < 150.0)
            .collect();
        homes.sort_by(|x, y| x.0.total_cmp(&y.0).then(x.1.cmp(&y.1)));
        let Some(&(_, j)) = homes.iter().find(|&&(_, j)| beside(l, &l.buildings[j])) else { continue };
        let (o, h) = (l.buildings[k].clone(), l.buildings[j].clone());
        let (to, from) = (&mut l.buildings[j], o);
        (to.func, to.name, to.floors, to.residential) = (from.func, from.name, from.floors, from.residential);
        let back = &mut l.buildings[k];
        (back.func, back.name, back.floors, back.residential) = (h.func, h.name, h.floors, h.residential);
        moved.extend([k, j]);
    }
}

/// Whether lot `poly` gives the footprint of temple `g` as it was generated (`shape`, either way).
pub(super) fn gives(poly: &[P], g: &Building) -> bool {
    let same = |a: &[P], b: &[P]| a.len() == b.len() && a.iter().zip(b).all(|(p, q)| dist(*p, *q) < 0.01);
    [false, true].iter().any(|&back| shape(poly, back, is_shrine(g)).is_some_and(|(p, _)| same(&p, &g.poly)))
}

/// Whether a building is a temple, a shrine or a monastery (its front door onto ground that reaches a
/// street: `street_reach`).
pub fn is_faith(b: &Building) -> bool {
    b.func.is_some_and(|f| matches!(catalog::CATALOG[f as usize].key, "temple" | "shrine" | "monastery"))
}

/// The battlemap's squares (5 ft, on the world's lattice) of the box round `pts` (world ft), `pad`
/// squares beyond them each way, whose open ground reaches a street of layout `l` over open ground,
/// square by square, as the battlemap has it: off every roofed building but `skip` (and the ground of
/// another's lots, `Layout::grounds`, but one `own` stands on) and off `own` (the building's footprint); the town wall left out,
/// so that taking it down changes no temple. `Reach::at` looks a point up.
pub fn street_reach(l: &Layout, skip: u32, own: &[P], pts: &[P], pad: usize) -> Reach {
    let sq = |v: f64| crate::core::floor(v / 5.0) as i64;
    let (mut x0, mut y0, mut x1, mut y1) = (i64::MAX, i64::MAX, i64::MIN, i64::MIN);
    for p in pts {
        (x0, y0, x1, y1) = (x0.min(sq(p[0])), y0.min(sq(p[1])), x1.max(sq(p[0])), y1.max(sq(p[1])));
    }
    let (x0, y0) = (x0 - pad as i64, y0 - pad as i64);
    let (w, h) = ((x1 + pad as i64 - x0 + 1) as usize, (y1 + pad as i64 - y0 + 1) as usize);
    let at = |i: usize, j: usize| [5.0 * (x0 + i as i64) as f64 + 2.5, 5.0 * (y0 + j as i64) as f64 + 2.5];
    let c = at(w / 2, h / 2);
    let r = 2.5 * (w + h) as f64 + 10.0;
    // (The polygons in the way, each with its box, those whose box meets the lattice's.)
    let bbox = |poly: &[P]| poly.iter().fold([f64::MAX, f64::MAX, f64::MIN, f64::MIN], |a, p| [a[0].min(p[0]), a[1].min(p[1]), a[2].max(p[0]), a[3].max(p[1])]);
    let all = [5.0 * x0 as f64, 5.0 * y0 as f64, 5.0 * (x0 + w as i64) as f64, 5.0 * (y0 + h as i64) as f64];
    let meets = |b: &[f64; 4]| b[0] <= all[2] && b[2] >= all[0] && b[1] <= all[3] && b[3] >= all[1];
    let roofed = |id: u32| l.building(id as usize).is_some_and(|o| o.structure == Structure::Roofed);
    let walls: Vec<(&[P], [f64; 4])> = l
        .buildings
        .iter()
        .filter(|o| o.id != skip && o.structure == Structure::Roofed)
        .map(|o| o.poly.as_slice())
        .chain(l.grounds.iter().filter(|g| g.0 != skip && roofed(g.0) && !(own.len() >= 3 && super::on_lot(&g.1, own))).map(|g| g.1.as_slice()))
        .chain((own.len() >= 3).then_some(own))
        .map(|poly| (poly, bbox(poly)))
        .filter(|(_, b)| meets(b))
        .collect();
    let lanes: Vec<(P, P, f64)> = l.roads.iter().flat_map(|(pts, _, wd)| pts.windows(2).map(move |s| (s[0], s[1], 0.5 * wd))).filter(|&(a, b, _)| super::geom::seg_dist(c, a, b) < r + 20.0).collect();
    let n = w * h;
    let mut open = vec![false; n];
    let mut seen = vec![false; n];
    let mut queue: std::collections::VecDeque<usize> = std::collections::VecDeque::new();
    for k in 0..n {
        let p = at(k % w, k / w);
        open[k] = !walls.iter().any(|(poly, b)| p[0] >= b[0] && p[0] <= b[2] && p[1] >= b[1] && p[1] <= b[3] && super::geom::contains(poly, p));
        if open[k] && lanes.iter().any(|&(a, b, hw)| super::geom::seg_dist(p, a, b) <= hw) {
            seen[k] = true;
            queue.push_back(k);
        }
    }
    while let Some(k) = queue.pop_front() {
        let (i, j) = (k % w, k / w);
        for (a, b) in [(i.wrapping_sub(1), j), (i + 1, j), (i, j.wrapping_sub(1)), (i, j + 1)] {
            if a < w && b < h && open[b * w + a] && !seen[b * w + a] {
                seen[b * w + a] = true;
                queue.push_back(b * w + a);
            }
        }
    }
    Reach { x0, y0, w, h, open, seen }
}

/// How far (squares) beyond a building its way to a street is looked for (`street_reach`).
pub const REACH_PAD: usize = 24;

/// Which battlemap squares round a building reach a street (`street_reach`).
#[derive(Clone, Debug)]
pub struct Reach {
    x0: i64,
    y0: i64,
    w: usize,
    h: usize,
    open: Vec<bool>,
    seen: Vec<bool>,
}

impl Reach {
    /// The square holding point `p` (world ft) is open and reaches a street (off the box: not).
    pub fn at(&self, p: P) -> bool {
        self.index(p).is_some_and(|k| self.seen[k])
    }

    /// The square holding point `p` is open ground (off the box: it is).
    pub fn open(&self, p: P) -> bool {
        self.index(p).is_none_or(|k| self.open[k])
    }

    /// The same box with no street in it to reach: its open squares that reach the box's edge over
    /// open ground (out of the houses round a hamlet's shrine) counted as reaching one.
    pub fn to_edge(mut self) -> Reach {
        let (w, h) = (self.w, self.h);
        let mut queue: std::collections::VecDeque<usize> = (0..w * h).filter(|&k| self.open[k] && (k % w == 0 || k / w == 0 || k % w == w - 1 || k / w == h - 1)).collect();
        self.seen = vec![false; w * h];
        for &k in &queue {
            self.seen[k] = true;
        }
        while let Some(k) = queue.pop_front() {
            let (i, j) = (k % w, k / w);
            for (a, b) in [(i.wrapping_sub(1), j), (i + 1, j), (i, j.wrapping_sub(1)), (i, j + 1)] {
                if a < w && b < h && self.open[b * w + a] && !self.seen[b * w + a] {
                    self.seen[b * w + a] = true;
                    queue.push_back(b * w + a);
                }
            }
        }
        self
    }

    fn index(&self, p: P) -> Option<usize> {
        let (i, j) = (crate::core::floor(p[0] / 5.0) as i64 - self.x0, crate::core::floor(p[1] / 5.0) as i64 - self.y0);
        (i >= 0 && j >= 0 && (i as usize) < self.w && (j as usize) < self.h).then(|| j as usize * self.w + i as usize)
    }
}
